// 205.17: the per-company and per-key OpenAPI 3.1 document, and its Postman
// export. It starts from the generated route table (publicAPIBaseDoc), drops
// what the key cannot reach, and adds what the table cannot say by itself: one
// schema per exposed document type (custom fields included), the actions, the
// reports and the events a key can subscribe to.

type apiSpecOptions struct {
	TenantCode string
	BaseURL    string
	Role       string                    // whose field visibility the schemas follow
	Row        *engines.APIKeyRow        // nil = everything the asker may give a key
	Modules    []engines.APIAccessModule // what the asker may see, from APIAccessModules
	Share      bool                      // a shared docs link: adds x-tenant-code
}

var apiSpecCommonErrors = []string{"APIKEY-0501", "APIKEY-0503", "APIKEY-0504", "APIKEY-0509", "APIKEY-0510"}

// apiSpecXErrors renders the catalogue rows for the codes an operation can answer.
func apiSpecXErrors(codes ...string) []interface{} {
	out := []interface{}{}
	for _, code := range codes {
		entry, ok := errorCatalog[code]
		if !ok {
			continue
		}
		out = append(out, map[string]interface{}{
			"code": code, "status": entry.HTTPStatus, "cause": entry.Scenario, "fix": entry.UserAction,
		})
	}
	return out
}

func apiSpecFieldSchema(f engines.FieldMeta) map[string]interface{} {
	s := map[string]interface{}{"description": f.Label}
	switch strings.ToLower(f.Fieldtype) {
	case "int", "integer":
		s["type"] = "integer"
	case "float", "currency", "percent", "decimal":
		s["type"] = "number"
	case "check", "boolean":
		s["type"] = "boolean"
	case "date":
		s["type"], s["format"] = "string", "date"
	case "datetime":
		s["type"], s["format"] = "string", "date-time"
	case "table":
		s["type"], s["items"] = "array", map[string]interface{}{"type": "object"}
	case "select":
		s["type"] = "string"
		var opts []string
		for _, o := range strings.Split(f.Options, "\n") {
			if o = strings.TrimSpace(o); o != "" {
				opts = append(opts, o)
			}
		}
		if len(opts) > 0 {
			s["enum"] = opts
		}
	default:
		s["type"] = "string"
		if f.MaxLength != nil {
			s["maxLength"] = *f.MaxLength
		}
	}
	return s
}

// apiSpecDoctypeSchema builds the record schema from the company's own fields,
// custom fields included, leaving out what the role may not see.
func apiSpecDoctypeSchema(tenantID, role, doctype string) map[string]interface{} {
	props := map[string]interface{}{
		"id":     map[string]interface{}{"type": "string", "description": "The record id."},
		"status": map[string]interface{}{"type": "string", "description": "The workflow status."},
	}
	required := []string{}
	fields, err := engines.GetDocTypeMeta(tenantID, doctype)
	if err == nil {
		hidden := map[string]bool{}
		if h, herr := engines.HiddenFieldsForRole(tenantID, role, doctype); herr == nil {
			for _, name := range h {
				hidden[name] = true
			}
		}
		for _, f := range fields {
			if hidden[f.Fieldname] || f.Fieldname == "" {
				continue
			}
			props[f.Fieldname] = apiSpecFieldSchema(f)
			if f.Mandatory && !f.AutoGenerated {
				required = append(required, f.Fieldname)
			}
		}
	}
	sort.Strings(required)
	schema := map[string]interface{}{"type": "object", "properties": props}
	if len(required) > 0 {
		schema["required"] = required
	}
	return schema
}

func apiSpecHasModule(opt apiSpecOptions, module string) (view, change bool) {
	if opt.Row != nil {
		level, ok := opt.Row.Modules[module]
		return ok, level == "write"
	}
	for _, m := range opt.Modules {
		if m.Key == module {
			return m.InPlan && m.CanView, m.InPlan && m.CanChange
		}
	}
	return false, false
}

func apiSpecDoctypeOn(opt apiSpecOptions, module, doctype string) bool {
	if opt.Row == nil {
		return true
	}
	list := opt.Row.Doctypes[module]
	if len(list) == 0 {
		return true
	}
	for _, d := range list {
		if d == doctype {
			return true
		}
	}
	return false
}

func apiSpecModuleName(opt apiSpecOptions, key string) string {
	for _, m := range opt.Modules {
		if m.Key == key {
			return m.Name
		}
	}
	return key
}

func apiSpecJSONBody(schemaRef string) map[string]interface{} {
	return map[string]interface{}{"content": map[string]interface{}{"application/json": map[string]interface{}{
		"schema": map[string]interface{}{"$ref": "#/components/schemas/" + schemaRef}}}}
}

// BuildAPISpec31 is the OpenAPI 3.1 document for opt.
func BuildAPISpec31(opt apiSpecOptions) map[string]interface{} {
	doc := publicAPIBaseDoc(true)
	tenantID := opt.TenantCode
	paths := doc["paths"].(map[string]interface{})
	comps := doc["components"].(map[string]interface{})
	schemas := comps["schemas"].(map[string]interface{})
	tenantParam := map[string]interface{}{"$ref": "#/components/parameters/TenantHeader"}

	// Routes the key cannot reach come out of the generated paths.
	for _, route := range publicAPIV1Routes() {
		if route.ModuleKey == "core" || route.ModuleKey == "reports" {
			continue
		}
		if view, _ := apiSpecHasModule(opt, route.ModuleKey); !view {
			delete(paths, route.Path)
		}
	}
	tags := []interface{}{}
	seenTag := map[string]bool{}
	addTag := func(name, desc string) {
		if !seenTag[name] {
			seenTag[name] = true
			tags = append(tags, map[string]interface{}{"name": name, "description": desc})
		}
	}
	// x-errors on every generated operation.
	for p, item := range paths {
		for _, op := range item.(map[string]interface{}) {
			opMap, ok := op.(map[string]interface{})
			if !ok {
				continue
			}
			codes := append([]string{}, apiSpecCommonErrors...)
			switch {
			case strings.Contains(p, "/records/"):
				codes = append(codes, "APIKEY-0505", "APIKEY-0506", "APIKEY-0507", "APIKEY-0508")
			case strings.Contains(p, "/actions/"):
				codes = append(codes, "APIKEY-0516")
			case strings.Contains(p, "/reports/"):
				codes = append(codes, "APIKEY-0517")
			}
			opMap["x-errors"] = apiSpecXErrors(codes...)
		}
	}

	schemas["WebhookEvent"] = map[string]interface{}{
		"type": "object",
		"properties": map[string]interface{}{
			"event":       map[string]interface{}{"type": "string", "description": "<module>.<Doctype>.<event>"},
			"tenant_code": map[string]interface{}{"type": "string"},
			"module":      map[string]interface{}{"type": "string"},
			"doctype":     map[string]interface{}{"type": "string"},
			"id":          map[string]interface{}{"type": "string"},
			"status":      map[string]interface{}{"type": "string"},
			"occurred_at": map[string]interface{}{"type": "string", "format": "date-time"},
			"record_url":  map[string]interface{}{"type": "string"},
		},
		"required": []string{"event", "tenant_code", "id", "occurred_at"},
	}

	webhooks := map[string]interface{}{}
	for _, m := range opt.Modules {
		view, change := apiSpecHasModule(opt, m.Key)
		if !m.InPlan {
			continue
		}
		if !view {
			continue
		}
		addTag(m.Name, m.Summary)
		for _, d := range m.Doctypes {
			if !apiSpecDoctypeOn(opt, m.Key, d.Doctype) {
				continue
			}
			ref := "Record_" + d.Doctype
			schemas[ref] = apiSpecDoctypeSchema(tenantID, opt.Role, d.Doctype)
			base := publicAPIPathPrefix + "records/" + d.Doctype
			base = strings.TrimSuffix(base, "/")
			list := map[string]interface{}{
				"summary":     "List " + d.Label,
				"operationId": "list" + d.Doctype,
				"tags":        []string{m.Name},
				"parameters":  []interface{}{tenantParam},
				"responses": map[string]interface{}{"200": map[string]interface{}{"description": "Success.",
					"content": map[string]interface{}{"application/json": map[string]interface{}{"schema": map[string]interface{}{
						"type": "object", "properties": map[string]interface{}{"data": map[string]interface{}{
							"type": "array", "items": map[string]interface{}{"$ref": "#/components/schemas/" + ref}}}}}}}},
				"x-errors": apiSpecXErrors(append(append([]string{}, apiSpecCommonErrors...), "APIKEY-0505", "APIKEY-0506", "APIKEY-0508")...),
			}
			one := map[string]interface{}{
				"summary":     "Get one " + d.Label,
				"operationId": "get" + d.Doctype,
				"tags":        []string{m.Name},
				"parameters": []interface{}{tenantParam, map[string]interface{}{
					"name": "id", "in": "path", "required": true, "schema": map[string]interface{}{"type": "string"}}},
				"responses": map[string]interface{}{"200": map[string]interface{}{"description": "Success.",
					"content": map[string]interface{}{"application/json": map[string]interface{}{"schema": map[string]interface{}{"$ref": "#/components/schemas/" + ref}}}}},
				"x-errors": apiSpecXErrors(append(append([]string{}, apiSpecCommonErrors...), "APIKEY-0505", "APIKEY-0506", "APIKEY-0508")...),
			}
			listItem := map[string]interface{}{"get": list}
			oneItem := map[string]interface{}{"get": one}
			if change && d.Class == engines.APIDoctypeRW {
				write := apiSpecJSONBody(ref)
				write["required"] = true
				listItem["post"] = map[string]interface{}{
					"summary": "Create " + d.Label, "operationId": "create" + d.Doctype, "tags": []string{m.Name},
					"parameters": []interface{}{tenantParam, map[string]interface{}{
						"name": "Idempotency-Key", "in": "header", "required": true, "schema": map[string]interface{}{"type": "string"}}},
					"requestBody": write,
					"responses": map[string]interface{}{"201": map[string]interface{}{"description": "Created.",
						"content": map[string]interface{}{"application/json": map[string]interface{}{"schema": map[string]interface{}{"$ref": "#/components/schemas/" + ref}}}}},
					"x-errors": apiSpecXErrors(append(append([]string{}, apiSpecCommonErrors...), "APIKEY-0505", "APIKEY-0506", "APIKEY-0507", "APIKEY-0508")...),
				}
				oneItem["put"] = map[string]interface{}{
					"summary": "Change " + d.Label, "operationId": "update" + d.Doctype, "tags": []string{m.Name},
					"parameters": []interface{}{tenantParam,
						map[string]interface{}{"name": "id", "in": "path", "required": true, "schema": map[string]interface{}{"type": "string"}},
						map[string]interface{}{"name": "Idempotency-Key", "in": "header", "required": true, "schema": map[string]interface{}{"type": "string"}}},
					"requestBody": write,
					"responses": map[string]interface{}{"200": map[string]interface{}{"description": "Saved.",
						"content": map[string]interface{}{"application/json": map[string]interface{}{"schema": map[string]interface{}{"$ref": "#/components/schemas/" + ref}}}}},
					"x-errors": apiSpecXErrors(append(append([]string{}, apiSpecCommonErrors...), "APIKEY-0505", "APIKEY-0506", "APIKEY-0507", "APIKEY-0508")...),
				}
			}
			paths[base] = listItem
			paths[base+"/{id}"] = oneItem

			for _, ev := range engines.APIDocumentEvents {
				name := m.Key + "." + d.Doctype + "." + ev
				webhooks[name] = map[string]interface{}{"post": map[string]interface{}{
					"summary":     d.Label + " " + ev,
					"description": "Sent to a webhook this key owns when a " + d.Label + " is " + ev + ". Signed with X-Webhook-Signature-256 (t=<unix>,v1=<hmac-sha256 of t.body>).",
					"tags":        []string{m.Name},
					"requestBody": apiSpecJSONBody("WebhookEvent"),
					"responses":   map[string]interface{}{"200": map[string]interface{}{"description": "Return any 2xx to acknowledge."}},
				}}
			}
		}
	}

	// Actions the key can use.
	for _, a := range publicActions {
		view, change := apiSpecHasModule(opt, a.Module)
		if !view || (a.Level == "write" && !change) {
			continue
		}
		addTag("Actions", "Reviewed screen actions run as the key owner.")
		path := publicAPIPathPrefix + "actions/" + a.Module + "/" + a.Action
		paths[path] = map[string]interface{}{"post": map[string]interface{}{
			"summary":     a.Summary,
			"description": "Body: " + a.Body,
			"operationId": "action_" + strings.ReplaceAll(a.Module+"_"+a.Action, "-", "_"),
			"tags":        []string{"Actions"},
			"parameters": []interface{}{tenantParam, map[string]interface{}{
				"name": "Idempotency-Key", "in": "header", "required": true, "schema": map[string]interface{}{"type": "string"}}},
			"requestBody": map[string]interface{}{"content": map[string]interface{}{"application/json": map[string]interface{}{
				"schema": map[string]interface{}{"type": "object"}}}},
			"responses": map[string]interface{}{"200": map[string]interface{}{"description": "Done."}},
			"x-errors":  apiSpecXErrors(append(append([]string{}, apiSpecCommonErrors...), "APIKEY-0516")...),
		}}
	}

	// Reports the key can run.
	for _, def := range engines.ListReportDefinitions() {
		if view, _ := apiSpecHasModule(opt, def.ModuleKey); !view || !engines.ReportAllowedForRole(def, engines.CanonicalRole(opt.Role)) {
			continue
		}
		addTag("Reports", "Reports from the report catalogue.")
		params := []interface{}{tenantParam,
			map[string]interface{}{"name": "format", "in": "query", "schema": map[string]interface{}{"type": "string", "enum": []string{"json", "csv"}}},
			map[string]interface{}{"name": "page", "in": "query", "schema": map[string]interface{}{"type": "integer"}},
			map[string]interface{}{"name": "page_size", "in": "query", "schema": map[string]interface{}{"type": "integer"}}}
		for _, p := range def.Params {
			params = append(params, map[string]interface{}{"name": p.Key, "in": "query", "required": p.Required, "description": p.Label, "schema": map[string]interface{}{"type": "string"}})
		}
		paths[publicAPIPathPrefix+"reports/"+def.ID] = map[string]interface{}{"get": map[string]interface{}{
			"summary": def.Label, "description": def.Question, "operationId": "report_" + strings.ReplaceAll(def.ID, "-", "_"),
			"tags": []string{"Reports"}, "parameters": params,
			"responses": map[string]interface{}{"200": map[string]interface{}{"description": "Rows."}},
			"x-errors":  apiSpecXErrors(append(append([]string{}, apiSpecCommonErrors...), "APIKEY-0517")...),
		}}
	}

	sort.SliceStable(tags, func(i, j int) bool {
		return tags[i].(map[string]interface{})["name"].(string) < tags[j].(map[string]interface{})["name"].(string)
	})
	doc["tags"] = tags
	if len(webhooks) > 0 {
		doc["webhooks"] = webhooks
	}
	base := strings.TrimRight(opt.BaseURL, "/")
	if base == "" {
		base = "/"
	}
	doc["servers"] = []interface{}{map[string]interface{}{"url": base, "description": "This deployment."}}
	info := doc["info"].(map[string]interface{})
	if opt.Row != nil {
		info["title"] = "ERP API: " + opt.Row.Name
	}
	info["description"] = fmt.Sprintf("%v\n\nSend X-Tenant-ID: %s on every call.", info["description"], opt.TenantCode)
	if opt.Share {
		doc["x-tenant-code"] = opt.TenantCode
	}
	return doc
}

// apiSpecPostman turns the spec into a Postman v2.1 collection: one folder per
// tag, the key and company code as variables so nothing secret is written in.
func apiSpecPostman(doc map[string]interface{}, name, tenantCode, baseURL string) map[string]interface{} {
	folders := map[string][]interface{}{}
	paths, _ := doc["paths"].(map[string]interface{})
	keys := make([]string, 0, len(paths))
	for p := range paths {
		keys = append(keys, p)
	}
	sort.Strings(keys)
	for _, p := range keys {
		item, _ := paths[p].(map[string]interface{})
		methods := make([]string, 0, len(item))
		for m := range item {
			methods = append(methods, m)
		}
		sort.Strings(methods)
		for _, m := range methods {
			op, ok := item[m].(map[string]interface{})
			if !ok {
				continue
			}
			tag := "General"
			if t, ok := op["tags"].([]string); ok && len(t) > 0 {
				tag = t[0]
			} else if t, ok := op["tags"].([]interface{}); ok && len(t) > 0 {
				tag, _ = t[0].(string)
			}
			upper := strings.ToUpper(m)
			headers := []interface{}{
				map[string]interface{}{"key": "Authorization", "value": "Bearer {{api_key}}"},
				map[string]interface{}{"key": "X-Tenant-ID", "value": "{{tenant_code}}"},
			}
			req := map[string]interface{}{"method": upper, "header": headers}
			if upper != http.MethodGet {
				req["header"] = append(headers, map[string]interface{}{"key": "Idempotency-Key", "value": "{{$guid}}"})
				if _, has := op["requestBody"]; has {
					req["body"] = map[string]interface{}{"mode": "raw", "raw": "{}",
						"options": map[string]interface{}{"raw": map[string]interface{}{"language": "json"}}}
				}
			}
			segs := strings.Split(strings.Trim(p, "/"), "/")
			for i, s := range segs {
				if strings.HasPrefix(s, "{") {
					segs[i] = ":" + strings.Trim(s, "{}")
				}
			}
			req["url"] = map[string]interface{}{"raw": "{{base_url}}" + p, "host": []string{"{{base_url}}"}, "path": segs}
			title, _ := op["summary"].(string)
			if title == "" {
				title = upper + " " + p
			}
			folders[tag] = append(folders[tag], map[string]interface{}{"name": title, "request": req})
		}
	}
	names := make([]string, 0, len(folders))
	for n := range folders {
		names = append(names, n)
	}
	sort.Strings(names)
	items := []interface{}{}
	for _, n := range names {
		items = append(items, map[string]interface{}{"name": n, "item": folders[n]})
	}
	return map[string]interface{}{
		"info": map[string]interface{}{
			"name":   name,
			"schema": "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
		},
		"variable": []interface{}{
			map[string]interface{}{"key": "base_url", "value": strings.TrimRight(baseURL, "/")},
			map[string]interface{}{"key": "tenant_code", "value": tenantCode},
			map[string]interface{}{"key": "api_key", "value": ""},
		},
		"item": items,
	}
}

func apiSpecWrite(w http.ResponseWriter, v interface{}) {
	w.Header().Set("Content-Type", "application/json")
	w.Header().Set("Cache-Control", "no-store")
	enc := json.NewEncoder(w)
	enc.SetIndent("", "  ")
	_ = enc.Encode(v)
}

// Command gencatalog turns the user's report catalog spec (Stage 75.3.2,
// docs/specs/reports/catalog_reports.tsv + catalog_columns.tsv) into
// engines/report_catalog_spec_generated.go: each catalog report's id, module,
// name, purpose and column list, in the catalog's order. The reports
// themselves are wired in engines/report_catalog*.go; a catalog report with
// no wiring is not registered (report-catalog-coverage.md says why).
// Stage 139.2: also every report's permanent number, from
// report_numbers.tsv in the same folder (reportNumbers).
//
// Usage:
//
//	go run ./cmd/gencatalog              # rewrite the generated file
//	go run ./cmd/gencatalog -check       # exit 1 if it is stale, write nothing
//	go run ./cmd/gencatalog -out FILE    # write somewhere else
//
// On this project's Windows dev machine, Controlled Folder Access blocks a
// freshly built binary from writing under Documents\ (see CLAUDE.md): use
// -out into %TEMP% and copy the file in.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"custom_erp/engines"
)

type report struct {
	id, module, group, name, grain, purpose string
	columns                                 []string
}

func readTSV(path string, minCols int, each func([]string)) error {
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		line := sc.Text()
		if line == "" || strings.HasPrefix(line, "#") || strings.HasPrefix(line, "report_id\t") {
			continue
		}
		parts := strings.Split(line, "\t")
		if len(parts) < minCols {
			return fmt.Errorf("%s: %q has %d fields, want %d", path, line, len(parts), minCols)
		}
		each(parts)
	}
	return sc.Err()
}

func main() {
	dir := flag.String("spec", filepath.Join("docs", "specs", "reports"), "directory holding catalog_reports.tsv and catalog_columns.tsv")
	out := flag.String("out", filepath.Join("engines", "report_catalog_spec_generated.go"), "file to write")
	check := flag.Bool("check", false, "compare against -out and exit 1 if it differs; write nothing")
	coverage := flag.String("coverage", "", "write the coverage document (docs/product/report-catalog-coverage.md) to this file instead")
	flag.Parse()
	if *coverage != "" {
		if err := os.WriteFile(*coverage, coverageDoc(), 0o644); err != nil {
			fail(err)
		}
		fmt.Printf("gencatalog: wrote %s\n", *coverage)
		return
	}

	var reports []*report
	byID := map[string]*report{}
	if err := readTSV(filepath.Join(*dir, "catalog_reports.tsv"), 6, func(p []string) {
		r := &report{id: p[0], module: p[1], group: p[2], name: p[3], grain: p[4], purpose: p[5]}
		reports = append(reports, r)
		byID[r.id] = r
	}); err != nil {
		fail(err)
	}
	if err := readTSV(filepath.Join(*dir, "catalog_columns.tsv"), 3, func(p []string) {
		if r := byID[p[0]]; r != nil {
			r.columns = append(r.columns, strings.TrimSpace(p[2]))
		}
	}); err != nil {
		fail(err)
	}

	var numbers [][2]string
	if err := readTSV(filepath.Join(*dir, "report_numbers.tsv"), 3, func(p []string) {
		if p[0] != "number" {
			numbers = append(numbers, [2]string{p[1], p[0]})
		}
	}); err != nil {
		fail(err)
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/gencatalog from docs/specs/reports/catalog_*.tsv and report_numbers.tsv. DO NOT EDIT.\n\npackage engines\n\n")
	b.WriteString("// catalogSpecs are the user's report catalog (Stage 75.3.2), in its order.\nvar catalogSpecs = []catalogSpec{\n")
	q := strconv.Quote
	for _, r := range reports {
		if len(r.columns) == 0 {
			fail(fmt.Errorf("%s has no columns in catalog_columns.tsv", r.id))
		}
		cols := make([]string, len(r.columns))
		for i, c := range r.columns {
			cols[i] = q(c)
		}
		fmt.Fprintf(&b, "\t{ID: %s, Module: %s, Group: %s, Name: %s, Grain: %s, Purpose: %s,\n\t\tColumns: []string{%s}},\n",
			q(r.id), q(r.module), q(r.group), q(r.name), q(r.grain), q(r.purpose), strings.Join(cols, ", "))
	}
	b.WriteString("}\n")
	b.WriteString("\n// reportNumbers is every report's permanent number (Stage 139.2), in report_numbers.tsv's order.\nvar reportNumbers = map[string]string{\n")
	for _, n := range numbers {
		fmt.Fprintf(&b, "\t%s: %s,\n", q(n[0]), q(n[1]))
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		fail(err)
	}
	if *check {
		cur, _ := os.ReadFile(*out)
		if !bytes.Equal(bytes.ReplaceAll(cur, []byte("\r\n"), []byte("\n")), src) {
			fmt.Fprintf(os.Stderr, "gencatalog: %s is stale - run go run ./cmd/gencatalog\n", *out)
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("gencatalog: wrote %s (%d reports, %d numbers)\n", *out, len(reports), len(numbers))
}

func fail(err error) {
	fmt.Fprintf(os.Stderr, "gencatalog: %v\n", err)
	os.Exit(2)
}

// coverageDoc is docs/product/report-catalog-coverage.md: every catalog
// report, built or waiting, with the columns the ERP cannot fill.
func coverageDoc() []byte {
	rows := engines.CatalogCoverage()
	var b bytes.Buffer
	built, cols, filled := 0, 0, 0
	byModule := map[string][2]int{}
	var modules []string
	for _, r := range rows {
		m := byModule[r.Module]
		if m == [2]int{} && !containsModule(modules, r.Module) {
			modules = append(modules, r.Module)
		}
		m[1]++
		if r.Built {
			built++
			m[0]++
			cols += r.Columns
			filled += r.Filled
		}
		byModule[r.Module] = m
	}
	b.WriteString("# Report catalog coverage\n\n")
	b.WriteString("<!-- GENERATED FILE - DO NOT EDIT BY HAND.\n     Source: engines.CatalogCoverage() (engines/report_catalog*.go) and docs/specs/reports/catalog_*.tsv\n     Regenerate: go run ./cmd/gencatalog -coverage docs/product/report-catalog-coverage.md -->\n\n")
	fmt.Fprintf(&b, "Stage 75.3: the user's two report catalogs (%d reports). **%d are built** - registered under their catalog id, with the catalog's columns in the catalog's order (held to `docs/specs/reports/catalog_columns.tsv` by `TestReportColumnsMatchCatalogSpec`). **%d wait for a module** that does not exist yet. ", len(rows), built, len(rows)-built)
	fmt.Fprintf(&b, "Of the built reports' %d columns, %d are filled from ERP data; the rest are in the report, blank, because the ERP does not record them (listed per report below).\n\n", cols, filled)
	b.WriteString("Reports open under **Reports → <catalog module>** (Sales & POS, Inventory, Procurement & GRN...), or search the report list by name.\n\n")
	b.WriteString("## By module\n\n| Module | Reports | Built | Waiting |\n|---|---:|---:|---:|\n")
	for _, m := range modules {
		v := byModule[m]
		fmt.Fprintf(&b, "| %s | %d | %d | %d |\n", m, v[1], v[0], v[1]-v[0])
	}
	cur := ""
	for _, r := range rows {
		if r.Module != cur {
			cur = r.Module
			fmt.Fprintf(&b, "\n## %s\n\n| Report | Id | Status | Columns filled | Blank (not held by the ERP) |\n|---|---|---|---:|---|\n", cur)
		}
		if !r.Built {
			fmt.Fprintf(&b, "| %s | `%s` | Waits: %s | - | - |\n", r.Name, r.ID, r.Note)
			continue
		}
		fmt.Fprintf(&b, "| %s | `%s` | Built | %d / %d | %s |\n", r.Name, r.ID, r.Filled, r.Columns, strings.Join(r.Blank, ", "))
	}
	return b.Bytes()
}

func containsModule(list []string, m string) bool {
	for _, x := range list {
		if x == m {
			return true
		}
	}
	return false
}

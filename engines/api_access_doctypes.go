// APIDoctypeClass is the class of a document type for API keys. A name that is
// not in the table (a Doctype Builder type) is read only until it is classed.
func APIDoctypeClass(doctype string) string {
	if class, ok := apiDoctypeClasses[doctype]; ok {
		return class
	}
	return APIDoctypeRO
}

// APIDoctypeClassKnown reports whether the shipped table classes the name.
func APIDoctypeClassKnown(doctype string) bool {
	_, ok := apiDoctypeClasses[doctype]
	return ok
}

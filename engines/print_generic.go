// Stage 127.3 (user, 2026-10-21: "all txn need print", "any new taxn should
// load properly in print"): every transaction prints. A doctype with a format
// of its own (PrintTransactions) keeps it; any other transactional doctype -
// one that is not a Master - prints through this generic format: its title,
// number, date, party and store, its header fields in form order and its
// lines, with each numeric column totalled. A transaction added later prints
// with no code. The print transaction key of a generic print is the doctype.

// PrintTxnDoctype is the doctype a print transaction prints from: a format's
// own doctype, else the key itself when it names a transactional doctype.
func PrintTxnDoctype(tenantID, txn string) string {
	if dt := printTxnDoctype(txn); dt != "" {
		return dt
	}
	if GenericPrintable(tenantID, txn) {
		return txn
	}
	return ""
}

// GenericPrintable says whether a doctype prints through the generic format:
// it exists, has fields, and is not a Master.
func GenericPrintable(tenantID, doctype string) bool {
	doctype = strings.TrimSpace(doctype)
	if doctype == "" || printTxnDoctype(doctype) != "" || !DoctypeIsTransaction(tenantID, doctype) {
		return false
	}
	fields, err := GetDocTypeMeta(tenantID, doctype)
	return err == nil && len(fields) > 0
}

// DoctypeIsTransaction says whether a doctype is a transaction, not a Master.
// A doctype with no type reads as a Master, as the menus read it
// (GetDocTypes), so nothing prints that the record form offers no Print for.
func DoctypeIsTransaction(tenantID, doctype string) bool {
	schema, err := db.GetTenantSchema(tenantID)
	if err != nil {
		return false
	}
	var transaction bool
	err = db.DB.QueryRow(fmt.Sprintf(`SELECT COALESCE(document_type, 'Master') <> 'Master' FROM %s.doctype_meta WHERE name = $1`, schema), doctype).Scan(&transaction)
	return err == nil && transaction
}

// genericPrintColumn is one column (or header row, or total) of the format.
type genericPrintColumn struct {
	Key    string `json:"key"`
	Label  string `json:"label"`
	Format string `json:"format,omitempty"`
}

// genericLineSkip are line keys the format never shows as a column.
var genericLineSkip = map[string]bool{"id": true, "line_id": true, "item": true, "attributes": true, "item_values": true}

// buildGenericPrint fills d for a generic print and returns the store the
// document was made at. The layout (trade-docs.js) reads
// fields.generic_print: its header rows, line columns and totals.
func buildGenericPrint(tenantID string, d *PrintDocument, data map[string]interface{}, cache map[string]map[string]interface{}, withImages bool) string {
	fields, _ := GetDocTypeMeta(tenantID, d.Doctype)
	sort.SliceStable(fields, func(i, j int) bool { return fields[i].DisplayOrder < fields[j].DisplayOrder })
	d.Title = humanizeDoctype(d.Doctype)

	number := ""
	for _, f := range fields {
		if f.AutoGenerated && strField(data, f.Fieldname) != "" {
			number = strField(data, f.Fieldname)
			break
		}
	}
	d.Number = firstNonEmpty(number, strField(data, "code"), strField(data, "number"), d.DocumentID)

	store := ""
	for _, f := range LocationReferenceFields[d.Doctype] {
		if store = strField(data, f); store != "" {
			break
		}
	}
	partyField := ""
	for _, f := range fields {
		v := strField(data, f.Fieldname)
		if f.Fieldtype != "Link" || v == "" {
			continue
		}
		switch f.Options {
		case "Location":
			if store == "" {
				store = v
			}
		case "Vendor":
			if partyField == "" {
				d.Vendor = v
				d.Party, d.PartyTitle, partyField = loadPrintVendor(tenantID, v), f.Label, f.Fieldname
			}
		case "Customer":
			if partyField == "" {
				d.Party, d.PartyTitle, partyField = loadPrintCustomer(tenantID, v), f.Label, f.Fieldname
			}
		case "Employee":
			if partyField == "" {
				emp, _, _ := fetchDocData(tenantID, "Employee", v)
				d.Party = PrintStore{Code: v, Name: firstNonEmpty(strField(emp, "full_name"), strField(emp, "name"), strField(emp, "employee_name"), v)}
				d.PartyTitle, partyField = f.Label, f.Fieldname
			}
		}
	}
	if d.Date == "" {
		for _, f := range fields {
			if f.Fieldtype == "Date" && strField(data, f.Fieldname) != "" {
				d.Date = strField(data, f.Fieldname)
				break
			}
		}
	}

	// Header rows: every filled scalar field in form order, a Link shown by
	// its record's name beside the code.
	var header []genericPrintColumn
	linesField := ""
	for _, f := range fields {
		switch {
		case f.Fieldtype == "JSONTable" || f.Fieldtype == "JSONMap":
			if linesField == "" && f.Fieldtype == "JSONTable" {
				linesField = f.Fieldname
			}
			continue
		case f.Fieldname == "status" || f.Fieldname == partyField || f.AutoGenerated:
			continue
		}
		v, ok := d.Fields[f.Fieldname]
		if !ok || v == nil || strings.TrimSpace(strField(d.Fields, f.Fieldname)) == "" && f.Fieldtype != "Number" && f.Fieldtype != "Check" {
			continue
		}
		key := f.Fieldname
		if f.Fieldtype == "Link" && f.Options != "" {
			if name := genericLinkName(tenantID, f.Options, strField(data, f.Fieldname)); name != "" {
				key = f.Fieldname + "__display"
				d.Fields[key] = name
			}
		}
		if f.Fieldtype == "Check" {
			key = f.Fieldname + "__display"
			if truthy(v) {
				d.Fields[key] = "Yes"
			} else {
				d.Fields[key] = "No"
			}
		}
		header = append(header, genericPrintColumn{Key: key, Label: firstNonEmpty(f.Label, humanizeField(f.Fieldname))})
	}

	// Lines: the doctype's line table, else an "items" / "lines" list.
	var lines []map[string]interface{}
	labels := map[string]string{}
	for _, name := range []string{linesField, "items", "lines"} {
		if name == "" {
			continue
		}
		if lines = genericLineList(data[name]); len(lines) > 0 {
			for _, f := range fields {
				if f.Fieldname == name {
					labels = jsonTableLabels(f.Options)
				}
			}
			break
		}
	}
	var keys []string
	seen := map[string]bool{}
	numeric := map[string]bool{}
	itemLines := false
	for _, l := range lines {
		for k, v := range l {
			if genericLineSkip[k] {
				continue
			}
			if _, isNum := v.(float64); isNum {
				numeric[k] = true
			}
			if !seen[k] {
				seen[k] = true
				keys = append(keys, k)
			}
		}
		if genericLineSKU(l) != "" {
			itemLines = true
		}
	}
	sort.Strings(keys)
	var columns []genericPrintColumn
	if itemLines {
		columns = []genericPrintColumn{{Key: "sr", Label: "#"}, {Key: "sku", Label: "SKU"}, {Key: "item_name", Label: "Item"}, {Key: "qty", Label: "Qty"}}
		for _, l := range lines {
			extra := map[string]interface{}{}
			for k, v := range l {
				if !genericLineSkip[k] {
					extra[k] = v
				}
			}
			qty := numFromInterface(firstPresent(l, "qty", "quantity", "received_qty", "issued_qty"))
			rate := numFromInterface(firstPresent(l, "rate", "unit_price", "price", "cost"))
			d.addLine(tenantID, printLineIn{SKU: genericLineSKU(l), Qty: qty, Rate: rate, Taxable: round2(qty * rate),
				MRP: numFromInterface(l["mrp"]), BatchNo: strField(l, "batch_no"), Extra: extra}, cache, withImages)
		}
		have := map[string]bool{"sku": true, "item_code": true, "item": true, "qty": true, "quantity": true, "item_name": true}
		for _, k := range keys {
			if !have[k] {
				columns = append(columns, genericPrintColumn{Key: k, Label: firstNonEmpty(labels[k], humanizeField(k))})
			}
		}
		if seen["rate"] || seen["unit_price"] || seen["price"] || seen["cost"] {
			columns = append(columns, genericPrintColumn{Key: "amount", Label: "Amount"})
		}
	} else {
		columns = []genericPrintColumn{{Key: "sr", Label: "#"}}
		for i, l := range lines {
			row := map[string]interface{}{"sr": i + 1}
			for k, v := range l {
				if !genericLineSkip[k] {
					row[k] = v
				}
			}
			d.Lines = append(d.Lines, row)
		}
		for _, k := range keys {
			columns = append(columns, genericPrintColumn{Key: k, Label: firstNonEmpty(labels[k], humanizeField(k))})
		}
	}
	if len(columns) > 9 {
		columns = columns[:9]
	}

	// Stage 127.3.1: a standard shape replaces the lines and columns.
	if shape, ok := printShapes[d.Doctype]; ok {
		d.Title = shape.title
		if shape.partyTitle != "" && partyField != "" {
			d.PartyTitle = shape.partyTitle
		}
		d.Lines = []map[string]interface{}{}
		numeric = map[string]bool{}
		for i, l := range shape.lines(tenantID, d.DocumentID, data) {
			row := map[string]interface{}{"sr": i + 1}
			for k, v := range l {
				row[k] = v
				if _, isNum := v.(float64); isNum {
					numeric[k] = true
				}
			}
			d.Lines = append(d.Lines, row)
		}
		columns = append([]genericPrintColumn{{Key: "sr", Label: "#"}}, shape.columns...)
		kept := header[:0]
		for _, h := range header {
			if !containsString(shape.hide, h.Key) {
				kept = append(kept, h)
			}
		}
		header = kept
	}

	// Totals: each quantity and value column shown, summed - never a rate,
	// price or percentage, whose sum means nothing.
	var totals []genericPrintColumn
	for _, c := range columns {
		if c.Key == "sr" || (!numeric[c.Key] && c.Key != "amount") {
			continue
		}
		format := "money"
		switch {
		case genericQtyKey.MatchString(c.Key):
			format = "qty"
		case !genericValueKey.MatchString(c.Key):
			continue
		}
		sum := 0.0
		for _, l := range d.Lines {
			sum += numFromInterface(l[c.Key])
		}
		d.Fields["total__"+c.Key] = round2(sum)
		totals = append(totals, genericPrintColumn{Key: "fields.total__" + c.Key, Label: "Total " + strings.ToLower(c.Label), Format: format})
	}
	d.Fields["generic_print"] = map[string]interface{}{"header": header, "columns": columns, "totals": totals}
	return store
}

// genericQtyKey and genericValueKey are the columns a total is made of.
var (
	genericQtyKey   = regexp.MustCompile(`(^|_)(qty|quantity|units|pieces|count|kg|weight)$`)
	genericValueKey = regexp.MustCompile(`(^|_)(amount|value|total|debit|credit|charge|cost_total|net|gross|tax|earning|deduction)$`)
)

// genericLineList reads a line table stored as a JSON string or a list.
func genericLineList(v interface{}) []map[string]interface{} {
	var out []map[string]interface{}
	switch x := v.(type) {
	case string:
		if s := strings.TrimSpace(x); strings.HasPrefix(s, "[") {
			_ = json.Unmarshal([]byte(s), &out)
		}
	case []interface{}:
		for _, e := range x {
			if m, ok := e.(map[string]interface{}); ok {
				out = append(out, m)
			}
		}
	}
	return out
}

func genericLineSKU(l map[string]interface{}) string {
	return firstNonEmpty(strField(l, "sku"), strField(l, "item_code"), strField(l, "item"))
}

func firstPresent(m map[string]interface{}, keys ...string) interface{} {
	for _, k := range keys {
		if v, ok := m[k]; ok && v != nil {
			return v
		}
	}
	return nil
}

// jsonTableLabels reads a JSONTable field's column labels from its options
// ([{"key": "...", "label": "..."}]), when it declares them.
func jsonTableLabels(options string) map[string]string {
	out := map[string]string{}
	var cols []struct {
		Key, Label, Fieldname string
	}
	if json.Unmarshal([]byte(options), &cols) == nil {
		for _, c := range cols {
			if k := firstNonEmpty(c.Key, c.Fieldname); k != "" && c.Label != "" {
				out[k] = c.Label
			}
		}
	}
	return out
}

// genericLinkName is a linked record shown as a person reads it: "Name (CODE)".
func genericLinkName(tenantID, doctype, id string) string {
	if strings.TrimSpace(id) == "" {
		return ""
	}
	rec, _, err := fetchDocData(tenantID, doctype, id)
	if err != nil {
		return ""
	}
	name := firstNonEmpty(strField(rec, "name"), strField(rec, "item_name"), strField(rec, "full_name"), strField(rec, "account_name"), strField(rec, "title"))
	if name == "" || name == id {
		return ""
	}
	return name + " (" + id + ")"
}

// humanizeDoctype turns "JournalVoucher" into "Journal Voucher" (an
// all-capitals run such as "RFQ" stays together).
func humanizeDoctype(s string) string {
	r := []rune(s)
	var b strings.Builder
	for i, c := range r {
		if i > 0 && unicode.IsUpper(c) && (unicode.IsLower(r[i-1]) || (i+1 < len(r) && unicode.IsLower(r[i+1]) && unicode.IsUpper(r[i-1]))) {
			b.WriteByte(' ')
		}
		b.WriteRune(c)
	}
	return b.String()
}

// humanizeField turns "debit_account" into "Debit account".
func humanizeField(s string) string {
	s = strings.ReplaceAll(strings.TrimSpace(s), "_", " ")
	if s == "" {
		return s
	}
	r := []rune(s)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}

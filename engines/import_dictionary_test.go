// cellIsFormulaSafe is what a spreadsheet must never see: a cell that starts
// with a formula character and is not a plain number.
func cellIsFormulaSafe(cell string) bool {
	t := strings.TrimLeft(cell, " \t")
	if t == "" || isPlainNumber(t) {
		return true
	}
	return !strings.ContainsRune("=+-@", rune(t[0]))
}

// Stage 47.13.2: every doctype's dictionary has one row per template column,
// in template order, and each row says what the importer really does with it.
func TestImportDictionaryCoversEveryDoctype(t *testing.T) {
	db.InitDB(testConnStr())
	rows, err := db.DB.Query(`SELECT DISTINCT doctype_name FROM tenant_default.doctype_fields ORDER BY 1`)
	if err != nil {
		t.Fatal(err)
	}
	var doctypes []string
	for rows.Next() {
		var d string
		_ = rows.Scan(&d)
		doctypes = append(doctypes, d)
	}
	rows.Close()
	if len(doctypes) < 50 {
		t.Fatalf("only %d doctypes with fields", len(doctypes))
	}
	for _, doctype := range doctypes {
		headers, err := importTemplateHeaders("default", doctype)
		if err != nil {
			t.Fatalf("%s template: %v", doctype, err)
		}
		specs, err := ImportTemplateDictionary("default", doctype)
		if err != nil {
			t.Fatalf("%s dictionary: %v", doctype, err)
		}
		fields, _ := GetDocTypeMeta("default", doctype)
		meta := map[string]FieldMeta{}
		for _, f := range fields {
			meta[f.Fieldname] = f
		}
		var cols []ImportColumnSpec
		var order *ImportColumnSpec
		for i, s := range specs {
			if s.Order > 0 {
				cols = append(cols, s)
			} else if s.Column == "(order)" {
				order = &specs[i]
			}
		}
		if len(cols) != len(headers) {
			t.Errorf("%s: %d dictionary rows for %d template columns", doctype, len(cols), len(headers))
			continue
		}
		for i, s := range cols {
			if s.Column != headers[i] || s.Order != i+1 {
				t.Errorf("%s: row %d is %q (order %d), template column is %q", doctype, i+1, s.Column, s.Order, headers[i])
			}
			if s.Type == "" || s.Definition == "" || s.Required == "" || s.OnUpdate == "" || s.Unique == "" {
				t.Errorf("%s.%s: incomplete row %+v", doctype, s.Column, s)
			}
			f, ok := meta[s.Column]
			if s.Column == "id" {
				if !strings.HasPrefix(s.Unique, "Yes") {
					t.Errorf("%s.id must be unique", doctype)
				}
				continue
			}
			if !ok {
				t.Errorf("%s: dictionary column %q is not a field", doctype, s.Column)
				continue
			}
			switch f.Fieldtype {
			case "Select":
				if want := strings.Join(splitOptions(f.Options), " | "); s.Allowed != want {
					t.Errorf("%s.%s allowed %q, want %q", doctype, s.Column, s.Allowed, want)
				}
			case "Link":
				if s.DependsOn != f.Options || order == nil || !strings.Contains(order.DependsOn, f.Options) {
					t.Errorf("%s.%s depends on %q; file order lists %v", doctype, s.Column, s.DependsOn, order)
				}
			case "Date":
				if s.Format != "YYYY-MM-DD" {
					t.Errorf("%s.%s date format %q", doctype, s.Column, s.Format)
				}
			}
			if f.Mandatory && !f.AutoGenerated && s.Required == "No" {
				t.Errorf("%s.%s is mandatory but the dictionary says not required", doctype, s.Column)
			}
		}
	}
}

// The dictionary CSV is itself formula-safe and names the destructive update.
func TestImportDictionaryCSV(t *testing.T) {
	db.InitDB(testConnStr())
	out, err := GenerateImportTemplateDictionaryCSV("default", "Vendor")
	if err != nil {
		t.Fatal(err)
	}
	records, err := csv.NewReader(bytes.NewReader(out)).ReadAll()
	if err != nil {
		t.Fatal(err)
	}
	if strings.Join(records[0], ",") != strings.Join(importDictionaryHeader, ",") {
		t.Errorf("header %v", records[0])
	}
	text := string(out)
	for _, want := range []string{"gstin", "REPLACES that record", "a blank cell or a column left out", "YYYY-MM-DD", "leading apostrophe", "Example: 27AAPFU0939F1ZV"} {
		if !strings.Contains(text, want) {
			t.Errorf("dictionary lacks %q", want)
		}
	}
	items, err := ImportTemplateDictionary("default", "Item")
	if err != nil {
		t.Fatal(err)
	}
	for _, s := range items {
		if s.Column == "tax_treatment" && s.Allowed != "Taxable | Exempt | Nil-Rated | Zero-Rated" {
			t.Errorf("Item.tax_treatment allowed %q", s.Allowed)
		}
		if s.Column == "family" && s.DependsOn != "ProductFamily" {
			t.Errorf("Item.family depends on %q", s.DependsOn)
		}
	}
	for _, r := range records {
		for _, c := range r {
			if !cellIsFormulaSafe(c) {
				t.Errorf("formula-shaped cell in the dictionary: %q", c)
			}
		}
	}
	if _, err := ImportTemplateDictionary("default", "NoSuchDoctype47132"); err == nil {
		t.Error("an unknown doctype produced a dictionary")
	}
}

// Template -> filled as a spreadsheet saves it (formula cells, commas, quotes,
// line breaks, accents, leading zeros) -> imported -> exported through the
// safe writer -> imported again: values survive, formulas are neutralised on
// the way in and never come back out live, and the second import changes
// nothing.
func TestImportTemplateSpreadsheetRoundTrip(t *testing.T) {
	db.InitDB(testConnStr())
	prefix := fmt.Sprintf("RT47132-%d", time.Now().UnixNano()%1_000_000)
	cleanup := func() {
		_, _ = db.DB.Exec(`DELETE FROM tenant_default.documents WHERE doctype = 'Vendor' AND id LIKE $1`, prefix+"%")
	}
	cleanup()
	defer cleanup()

	tmpl, err := GenerateCSVTemplate("default", "Vendor")
	if err != nil {
		t.Fatal(err)
	}
	header, err := csv.NewReader(bytes.NewReader(tmpl)).Read()
	if err != nil {
		t.Fatal(err)
	}
	filled := []map[string]string{
		{"code": prefix + "-1", "name": `Café, "Best" Supplies`, "gstin": synthGSTIN("29", 4242), "bank_account_number": "000123456789",
			"bank_ifsc": "HDFC0001234", "contact_email": "buyer@example.com", "address": `=HYPERLINK("http://evil.example","click")`,
			"address_line2": `+cmd|' /C calc'!A0`, "city": "@SUM(1)", "state": "Karnataka", "pincode": "560001"},
		{"code": prefix + "-2", "name": "Ünïcödé Traders\nSecond line", "address": "-2+3", "city": "-12.50", "state": "Karnataka", "pincode": "560002"},
	}
	var in bytes.Buffer
	w := csv.NewWriter(&in) // a spreadsheet's own save: no escaping of formulas
	_ = w.Write(header)
	for _, row := range filled {
		rec := make([]string, len(header))
		for i, h := range header {
			rec[i] = row[h]
		}
		_ = w.Write(rec)
	}
	w.Flush()

	res, err := BulkImportCSV("default", "Vendor", bytes.NewReader(in.Bytes()), "system", "", false)
	if err != nil || res.SuccessRows != 2 {
		t.Fatalf("first import: %v %+v", err, res)
	}
	stored := func() map[string]map[string]interface{} {
		t.Helper()
		out := map[string]map[string]interface{}{}
		rows, err := db.DB.Query(`SELECT id, data FROM tenant_default.documents WHERE doctype = 'Vendor' AND id LIKE $1 ORDER BY id`, prefix+"%")
		if err != nil {
			t.Fatal(err)
		}
		defer rows.Close()
		for rows.Next() {
			var id string
			var raw []byte
			_ = rows.Scan(&id, &raw)
			var m map[string]interface{}
			_ = json.Unmarshal(raw, &m)
			out[id] = m
		}
		return out
	}
	first := stored()
	v1, v2 := first[prefix+"-1"], first[prefix+"-2"]
	if v1 == nil || v2 == nil {
		t.Fatalf("imported rows not found: %v", first)
	}
	for field, want := range map[string]string{"name": `Café, "Best" Supplies`, "bank_account_number": "000123456789",
		"address": `'=HYPERLINK("http://evil.example","click")`, "address_line2": `'+cmd|' /C calc'!A0`, "city": "'@SUM(1)"} {
		if got := fmt.Sprint(v1[field]); got != want {
			t.Errorf("row 1 %s = %q, want %q", field, got, want)
		}
	}
	for field, want := range map[string]string{"name": "Ünïcödé Traders\nSecond line", "address": "'-2+3", "city": "-12.50"} {
		if got := fmt.Sprint(v2[field]); got != want {
			t.Errorf("row 2 %s = %q, want %q", field, got, want)
		}
	}

	// Export in template order through the safe writer, as a person gets it.
	var exported bytes.Buffer
	sw := newSafeCSVWriter(&exported)
	_ = sw.Write(header)
	for _, id := range []string{prefix + "-1", prefix + "-2"} {
		rec := make([]string, len(header))
		for i, h := range header {
			if h == "id" {
				rec[i] = id
			} else if v, ok := first[id][h]; ok && v != nil {
				rec[i] = fmt.Sprint(v)
			}
		}
		_ = sw.Write(rec)
	}
	sw.Flush()
	back, err := csv.NewReader(bytes.NewReader(exported.Bytes())).ReadAll()
	if err != nil {
		t.Fatal(err)
	}
	for _, r := range back {
		for _, c := range r {
			if !cellIsFormulaSafe(c) {
				t.Errorf("exported cell would run as a formula: %q", c)
			}
		}
	}
	res, err = BulkImportCSV("default", "Vendor", bytes.NewReader(exported.Bytes()), "system", "", false)
	if err != nil || res.SuccessRows != 2 || len(res.UpdatedIDs) != 2 {
		t.Fatalf("re-import: %v %+v", err, res)
	}
	if second := stored(); !reflect.DeepEqual(first, second) {
		t.Errorf("the round trip changed the records:\nfirst  %v\nsecond %v", first, second)
	}
}

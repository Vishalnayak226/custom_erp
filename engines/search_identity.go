package engines

import "strings"

// Stage 127.7 (user, 2026-10-21: "Make erp rock solid ... everywhere fix the
// bug"): the user's 94.24 bug - a picker typing "A" listed every record whose
// status reads "Active" - was fixed on the PO screen only, with q_fields. A
// picker finds a record by what identifies it, so every link typeahead now
// asks for q_fields=@identity: the doctype's code, name, number and contact
// fields, never a status, category, description or JSON field.

// searchIdentityNames are the fieldnames that identify a record wherever
// they appear.
var searchIdentityNames = map[string]bool{
	"id": true, "code": true, "name": true, "title": true, "full_name": true, "item_name": true, "display_name": true,
	"sku": true, "barcode": true, "phone": true, "mobile": true, "contact_phone": true, "email": true, "gstin": true,
	"pan": true, "account_code": true, "account_name": true, "employee_name": true, "customer_name": true, "vendor_name": true,
	"short_code": true,
}

// SearchIdentityFields lists the fields @identity stands for on a doctype:
// the names above it has, its server-numbered fields, and any Data field
// named *_number / *_no (not a bank account).
func SearchIdentityFields(tenantID, doctype string) []string {
	out := []string{"id", "code", "name"}
	seen := map[string]bool{"id": true, "code": true, "name": true}
	fields, err := GetDocTypeMeta(tenantID, doctype)
	if err != nil {
		return out
	}
	for _, f := range fields {
		n := f.Fieldname
		if seen[n] {
			continue
		}
		// A *_code field (state, price list, HSN) is shared by many records,
		// and a bank account is not how anyone looks a record up.
		numbered := f.Fieldtype == "Data" && (strings.HasSuffix(n, "_number") || strings.HasSuffix(n, "_no")) && !strings.HasPrefix(n, "bank_")
		if searchIdentityNames[n] || f.AutoGenerated || numbered {
			seen[n] = true
			out = append(out, n)
		}
	}
	return out
}

"""Build public/pin-directory.json: India's states -> districts -> PIN codes.

The till's customer form (item 261.1/261.2) offers a City list once a State is
picked and a PIN list once a City is picked; typing anything else still works.

Source: India Post "All India Pincode Directory" CSV from data.gov.in
(Government Open Data Licence - India). Download it, then run:

    py -I scripts/gen_pin_directory.py <pincode.csv> public/pin-directory.json

State names are written exactly as engines/regions.go names them, so the keys
match what the State list stores. A district is offered as the city.
"""
import csv
import json
import re
import sys

APP_STATES = [
    "Jammu and Kashmir", "Himachal Pradesh", "Punjab", "Chandigarh", "Uttarakhand",
    "Haryana", "Delhi", "Rajasthan", "Uttar Pradesh", "Bihar", "Sikkim",
    "Arunachal Pradesh", "Nagaland", "Manipur", "Mizoram", "Tripura", "Meghalaya",
    "Assam", "West Bengal", "Jharkhand", "Odisha", "Chhattisgarh", "Madhya Pradesh",
    "Gujarat", "Dadra and Nagar Haveli and Daman and Diu", "Maharashtra", "Karnataka",
    "Goa", "Lakshadweep", "Kerala", "Tamil Nadu", "Puducherry",
    "Andaman and Nicobar Islands", "Telangana", "Andhra Pradesh", "Ladakh",
]
SMALL = {"and", "of", "the"}
# Cities people type that the directory splits into districts.
WHOLE_STATE_CITY = {"Delhi": "Delhi"}


def title(s):
    words = re.sub(r"\s+", " ", s.strip().lower())
    out, first = [], True

    def cap(m):
        nonlocal first
        w = m.group(0)
        r = w if (not first and w in SMALL) else w[0].upper() + w[1:]
        first = False
        return r

    return re.sub(r"[a-z][a-z']*", cap, words)


def main(src, dst):
    by_lower = {n.lower(): n for n in APP_STATES}
    states, unmapped = {}, {}
    with open(src, newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            pin = (row.get("Pincode") or "").strip()
            dist = (row.get("District") or "").strip()
            st = re.sub(r"^the ", "", (row.get("StateName") or "").strip().lower())
            if not re.fullmatch(r"[1-9]\d{5}", pin) or not dist or dist == "NA":
                continue
            state = by_lower.get(st)
            if not state:
                unmapped[st] = unmapped.get(st, 0) + 1
                continue
            d = states.setdefault(state, {})
            d.setdefault(title(dist), set()).add(pin)
            if state in WHOLE_STATE_CITY:
                d.setdefault(WHOLE_STATE_CITY[state], set()).add(pin)
    if unmapped:
        sys.exit(f"state names not in engines/regions.go: {unmapped}")
    missing = [s for s in APP_STATES if s not in states]
    doc = {
        "source": "India Post All India Pincode Directory, data.gov.in (Government Open Data Licence - India). Generated by scripts/gen_pin_directory.py; do not edit by hand.",
        "states": {s: {d: " ".join(sorted(p)) for d, p in sorted(states[s].items())} for s in sorted(states)},
    }
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        json.dump(doc, f, ensure_ascii=False, separators=(",", ":"))
    n = sum(len(v) for v in doc["states"].values())
    print(f"{len(doc['states'])} states, {n} cities; missing: {missing or 'none'}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
